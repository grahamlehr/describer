/** Text as an array of column bitmaps, 7 bits each, one bit per dot row. */
export function columnsFor(text) {
  const columns = [];
  for (const char of text) {
    const rows = GLYPHS[char] || GLYPHS['?'];
    for (let x = 0; x < 5; x += 1) {
      let bits = 0;
      for (let y = 0; y < 7; y += 1) if (rows[y] & (0x10 >> x)) bits |= 1 << y;
      columns.push(bits);
    }
    columns.push(0); // the gap column between characters
  }
  return columns;
}

export function normalise(text, chars, right = false) {
  const fitted = printable(fit(String(text), chars).toUpperCase());
  return right ? fitted.padStart(chars, ' ') : fitted.padEnd(chars, ' ');
}

/** Anything the 5x7 font has no glyph for is a blank dot, not a query mark. */
function printable(text) {
  return text.replace(/[^0-9A-Z&:.,'\-\/()• ]/g, ' ');
}

/** Shorten a name only as far as it takes to fit the columns we have. */
export function fit(text, chars) {
  if (text.length <= chars) return text;
  let shortened = text;
  for (const [pattern, replacement] of ABBREVIATIONS) {
    shortened = shortened.replace(pattern, replacement).trim();
    if (shortened.length <= chars) return shortened;
  }
  return shortened.slice(0, chars);
}

/**
 * Pack items into lines of at most `chars` characters, never splitting one
 * across a page. A board that cannot scroll turns pages instead; an item
 * longer than the whole line is the one case that has to be cut.
 */
export function paginate(items, separator, chars) {
  if (!chars) return [];
  const pages = [];
  let line = '';
  for (const item of items) {
    const joined = line ? line + separator + item : item;
    if (joined.length <= chars) {
      line = joined;
      continue;
    }
    if (line) pages.push(line);
    line = item.length <= chars ? item : item.slice(0, chars);
  }
  if (line) pages.push(line);
  return pages;
}
